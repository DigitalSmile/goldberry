/*
 * The layout probe for goldberry-media.
 *
 * Prints, as a Java properties file, the size and alignment of every upstream
 * struct the Java side allocates or reads, the offset and size of every field it
 * touches, and the constants it hard-codes. The media superbuild compiles and
 * runs it once per platform and packages the output beside the library;
 * `NativeLayouts` in Java is checked against it by a unit test and again, once,
 * before anything native is touched.
 *
 * It is compiled against the headers of the libraries it describes and links
 * nothing: every value is a compile-time constant. That is also why it can run
 * on a machine that has headers and no library.
 *
 * Usage: media_layout [output-file]. With no argument it writes to stdout; the
 * superbuild passes a path, so no shell redirection has to survive CMake's
 * quoting on four generators.
 *
 * Keys:
 *   struct.<Name>.sizeof / struct.<Name>.alignof
 *   field.<Name>.<field>.offset / field.<Name>.<field>.sizeof
 *   const.<NAME>
 *   abi
 */
