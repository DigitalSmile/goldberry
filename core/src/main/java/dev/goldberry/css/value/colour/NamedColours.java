    private NamedColours() {}

    /// The colour `name` names, in any case, or null.
    public static @Nullable Integer get(String name) {
        var rgb = RGB.get(name.toLowerCase(Locale.ROOT));
        return rgb == null ? null : 0xFF000000 | rgb;
    }

