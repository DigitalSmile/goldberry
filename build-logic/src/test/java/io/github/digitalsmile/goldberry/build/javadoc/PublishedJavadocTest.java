package io.github.digitalsmile.goldberry.build.javadoc;

import io.github.digitalsmile.goldberry.build.repository.Repository;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;

import java.util.regex.Pattern;

import static org.junit.jupiter.api.Assertions.assertAll;
import static org.junit.jupiter.api.Assertions.assertTrue;

/**
 * The javadoc of the published modules is linted, and linted <em>early</em> --
 * ADR-0343 and ADR-0405, held as text (ADR-0082).
 *
 * <p>Both halves fail quietly when broken, and the second one already did. With
 * the lint on but nothing generating javadoc before {@code javadocJar}, a broken
 * {@code [link]} passed every {@code build} on all three operating systems and
 * surfaced in the last step of the last job of {@code publish.yml} -- partway
 * through an upload, with three modules already on Central's snapshot repository.
 * The thing that makes the lint useful is not that it is on; it is that
 * {@code check} runs it.
 */
@DisplayName("the published javadoc")
class PublishedJavadocTest {

    /** The convention plugin that both rules live in. */
    private static final String PLUGIN = "build-logic/src/main/groovy/goldberry.publish.gradle";

    /**
     * {@code dependsOn tasks.named('javadoc')}, allowing any run of spaces and a
     * single or double quoted task name -- the wiring is the assertion, not the
     * Groovy dialect it is written in.
     */
    private static final Pattern CHECK_RUNS_JAVADOC =
            Pattern.compile("dependsOn\\s+tasks\\.named\\(\\s*['\"]javadoc['\"]\\s*\\)");

    @Test
    @DisplayName("is linted, less the `missing` group")
    void doclintIsOn() {
        var text = Repository.read(PLUGIN);
        assertTrue(text.contains("Xdoclint:all,-missing"),
                "goldberry.publish no longer passes -Xdoclint:all,-missing, so a rotted [link] in a"
                        + " published module is a warning nobody reads (ADR-0343)");
    }

    @Test
    @DisplayName("is generated by `check`, so an ordinary build finds a broken link")
    void checkGeneratesJavadoc() {
        var text = Repository.read(PLUGIN);
        assertAll(
                () -> assertTrue(CHECK_RUNS_JAVADOC.matcher(text).find(),
                        "nothing makes `check` generate javadoc, so the only thing that does is"
                                + " `javadocJar` in publish.yml's last step -- the release's last step is"
                                + " the first to find a broken [link] again (ADR-0405)"),
                // The guard that keeps `:bom` out of it. A bare `tasks.named('check')`
                // at the top level of this plugin fails configuration of the platform,
                // which has no `javadoc` task at all -- and that failure is every
                // Gradle invocation, not just a publish.
                () -> assertTrue(text.contains("pluginManager.withPlugin('java-library')"),
                        "the javadoc wiring must stay under a java-library guard; :bom is a"
                                + " java-platform and has no javadoc task to depend on"));
    }
}
