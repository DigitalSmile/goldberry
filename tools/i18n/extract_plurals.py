#!/usr/bin/env python3
"""Extracts CLDR's plural rules into the resource dev.goldberry.i18n reads.

    python3 tools/i18n/extract_plurals.py plurals.json ordinals.json \
        core/src/main/resources/dev/goldberry/i18n/plurals.txt

The two inputs are cldr-json's supplemental files at the pinned tag below,
downloaded by hand and checked against their SHA-256 before anything is read:

    https://raw.githubusercontent.com/unicode-org/cldr-json/49.0.0/cldr-json/cldr-core/supplemental/plurals.json
    https://raw.githubusercontent.com/unicode-org/cldr-json/49.0.0/cldr-json/cldr-core/supplemental/ordinals.json

The output is one rule per line, tab-separated: type, locale, category, and the
rule as CLDR writes it, samples included -- the samples are what the tests
check every rule against. Unicode License v3 (licenses/unicode.txt).
"""

import hashlib
import json
import sys

CLDR_VERSION = "49.0.0"
SHA256 = {
    "plurals": "166cc4c4d7f45a3888c781e4e48974aab40f50bd42e592eacdcc79419f280353",
    "ordinals": "3d2b2e70009e0d655f459683d1a32a124b13e75438c7ddc084e6597d3b460e6a",
}
ORDER = ["zero", "one", "two", "few", "many", "other"]


def load(path, name):
    data = open(path, "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256[name]:
        sys.exit(f"{path}: SHA-256 {digest}, expected {SHA256[name]} for CLDR {CLDR_VERSION} {name}.json")
    return json.loads(data)


def rows(document, key, kind):
    table = document["supplemental"][key]
    for locale in sorted(table):
        rules = table[locale]
        by_category = {name.removeprefix("pluralRule-count-"): text for name, text in rules.items()}
        for category in sorted(by_category, key=ORDER.index):
            rule = " ".join(by_category[category].split())
            yield f"{kind}\t{locale}\t{category}\t{rule}"


def main():
    if len(sys.argv) != 4:
        sys.exit(__doc__)
    plurals = load(sys.argv[1], "plurals")
    ordinals = load(sys.argv[2], "ordinals")
    lines = [
        f"# CLDR {CLDR_VERSION} plural rules, Unicode License v3 (licenses/unicode.txt).",
        "# Generated by tools/i18n/extract_plurals.py; do not edit.",
        "# type\tlocale\tcategory\trule",
    ]
    lines += rows(plurals, "plurals-type-cardinal", "cardinal")
    lines += rows(ordinals, "plurals-type-ordinal", "ordinal")
    with open(sys.argv[3], "w", encoding="utf-8", newline="\n") as out:
        out.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
